import { expect, type Page } from "@playwright/test";
import type { Draft } from "../../lib/video-space/contract";

export async function richDraftJourney(page: Page, read: () => Promise<Draft>, screenshot: (name: string) => string) {
  const title = page.getByRole("textbox", { name: "文稿标题", exact: true });
  const body = page.getByRole("textbox", { name: "文稿正文" });
  const tools = page.getByRole("toolbar", { name: "文本格式" });
  await title.fill("手写的终稿标题");
  await body.fill("编辑札记");
  await tools.getByLabel("段落样式").selectOption("2");
  await expect(body.locator("h2")).toHaveText("编辑札记");
  await body.press("End");
  await body.press("Enter");
  await page.keyboard.insertText("这是作者手写的正文。");
  await body.press("Home");
  await body.press("Shift+End");
  await tools.getByRole("button", { name: "加粗", exact: true }).click();
  await expect(body.locator("strong")).toHaveText("这是作者手写的正文。");
  await tools.getByLabel("撤销输入或格式").click();
  await expect(body.locator("strong")).toHaveCount(0);
  await tools.getByLabel("重做").click();
  await expect(body.locator("strong")).toHaveText("这是作者手写的正文。");
  await body.press("End");
  await body.press("Enter");
  await tools.getByLabel("项目符号列表").click();
  await page.keyboard.insertText("参考资料");
  await body.press("Home");
  await body.press("Shift+End");
  await tools.getByRole("button", { name: "链接", exact: true }).click();
  await tools.getByLabel("链接地址").fill("https://example.org/source");
  await tools.getByRole("button", { name: "应用", exact: true }).click();
  await expect(body.locator("li a")).toHaveAttribute("href", "https://example.org/source");
  await body.press("End");
  await body.press("Enter");
  await body.press("Enter");
  await tools.getByLabel("更多格式").click();
  await tools.getByLabel("表格", { exact: true }).selectOption("insertTable");
  await expect(body.locator("tr")).toHaveCount(2);
  await expect(body.locator("td")).toHaveCount(4);
  await body.locator("td").first().click();
  await page.keyboard.insertText("来源");
  await tools.getByLabel("表格", { exact: true }).selectOption("addColumn");
  await expect(body.locator("td")).toHaveCount(6);
  await tools.getByLabel("更多格式").click();
  await expect.poll(read).toMatchObject({ title: "手写的终稿标题", text: expect.stringContaining("来源"),
    formatting: expect.arrayContaining([expect.objectContaining({ attributes: expect.objectContaining({ bold: true }) })]) });
  await page.getByRole("region", { name: "当前文稿" }).screenshot({ path: screenshot("rich-desktop") });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await expect(title).toHaveValue("手写的终稿标题");
  await expect(body.locator("h2")).toHaveText("编辑札记");
  await expect(body.locator("strong").first()).toHaveText("这是作者手写的正文。");
  await expect(body.locator("li a")).toHaveAttribute("href", "https://example.org/source");
  await expect(body.locator("tr")).toHaveCount(2);
  await expect(body.locator("td")).toHaveCount(6);
  await expect(body.locator("td").first()).toHaveText("来源");
  await body.locator("td").first().click();
  await page.keyboard.insertText("甲");
  await expect.poll(read).toMatchObject({ text: expect.stringContaining("甲") });
  await expect(tools).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.getByRole("region", { name: "当前文稿" }).screenshot({ path: screenshot("rich-mobile") });
}
